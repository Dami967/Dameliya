export function builtInUiTranslation(language: string, source: string) {
  const text = source.trim();
  const dictionary = language === 'en' ? english : language === 'kk' ? kazakh : undefined;
  const direct = dictionary?.[text];
  if (direct) return direct;
  const greeting = text.match(/^Привет, (.+)!\s*👋$/);
  if (greeting && language === 'en') return `Hi, ${greeting[1]}! 👋`;
  if (greeting && language === 'kk') return `Сәлем, ${greeting[1]}! 👋`;
  const level = text.match(/^Уровень (\d+)$/);
  if (level && language === 'en') return `Level ${level[1]}`;
  if (level && language === 'kk') return `${level[1]}-деңгей`;
  return undefined;
}
