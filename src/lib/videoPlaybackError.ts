export function videoPlaybackError(code: number, supportsH264: boolean) {
  if (code === 5) return supportsH264
    ? 'Плеер не смог запустить видео. Повтори запуск. Если ошибка остаётся у разных уроков, открой GoalQuest в обычном браузере.'
    : 'Этот браузер не поддерживает нужный формат видео. Открой сам GoalQuest в Chrome или Safari — урок останется внутри приложения.';
  if (code === 100) return 'Этот ролик удалён или стал закрытым. Подбери другой урок по этой теме.';
  if (code === 101 || code === 150) return 'Автор запретил просмотр этого ролика внутри приложений. Подбери другой урок.';
  if (code === 153) return 'YouTube не получил адрес приложения. Открой GoalQuest в обычном браузере и повтори запуск.';
  return `Не удалось запустить плеер (код ${code}). Попробуй повторить.`;
}
